class _DOMAuditParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.ids: set[str] = set()
        self.links: list[str] = []
        self.imgs: list[dict[str, str]] = []
        self.svgs: list[dict[str, str | bool]] = []
        self._svg_stack: list[dict[str, str | bool]] = []
        self._in_svg_title = False
        self._svg_title_buf: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        adict = {k: (v or "") for k, v in attrs}
        if adict.get("id"):
            self.ids.add(adict["id"])
        if tag in ("a", "link") and "href" in adict:
            self.links.append(adict["href"])
        if tag in ("script", "img", "source") and "src" in adict:
            self.links.append(adict["src"])
        if tag == "img":
            self.imgs.append(adict)
        if tag == "svg":
            rec: dict[str, str | bool] = {
                "hidden": adict.get("aria-hidden") == "true",
                "aria_label": adict.get("aria-label", "").strip(),
                "has_title": False,
            }
            self._svg_stack.append(rec)
        if tag == "title" and self._svg_stack:
            self._in_svg_title = True
            self._svg_title_buf = []

    def handle_data(self, data: str) -> None:
        if self._in_svg_title:
            self._svg_title_buf.append(data)

    def handle_endtag(self, tag: str) -> None:
        if tag == "title" and self._in_svg_title:
            if self._svg_stack and "".join(self._svg_title_buf).strip():
                self._svg_stack[-1]["has_title"] = True
            self._in_svg_title = False
        if tag == "svg" and self._svg_stack:
            self.svgs.append(self._svg_stack.pop())


