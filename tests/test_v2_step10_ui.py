def test_r12_flagship_site_build_links_copy_alt_and_features(tmp_path: Path) -> None:
    """Full site build satisfies C2 copy, alt text, internal links, product pages, sorting, and pack links."""
    out = tmp_path / "site_out"
    manifest = build_site(ROOT, out, built_at="2026-11-25T15:30:00+00:00")
    for page in EXPECTED_PAGES:
        assert (out / page).is_file(), f"missing built page {page}"
        assert page in manifest["bytes"]

    parsed: dict[str, _DOMAuditParser] = {}
    for hp in sorted(out.glob("*.html")):
        txt = hp.read_text(encoding="utf-8")
        # Copy hygiene gates (fail on em dash, Rank #, banned AI wording).
        assert "\u2014" not in txt and "&mdash;" not in txt, f"em dash found in {hp.name}"
        assert "Rank #" not in txt, f"Rank # found in {hp.name}"
        assert not re.search(r"\b(ai[- ]generated|as an ai|generated by ai)\b", txt, re.I), (
            f"banned AI phrase found in {hp.name}"
        )

        p = _DOMAuditParser()
        p.feed(txt)
        parsed[hp.name] = p

        # Alt text / SVG text-alternative gate.
        for im in p.imgs:
            assert im.get("alt", "").strip(), f"img missing alt in {hp.name}: {im}"
        for sv in p.svgs:
            if not sv["hidden"]:
                assert sv["aria_label"] or sv["has_title"], f"visible svg missing label in {hp.name}"

        # Shared navigation & footer checks on every page.
        assert 'href="method.html"' in txt and 'href="method.html#limits"' in txt
        assert "v2.0.0-rc1" in txt
        assert "Apache-2.0 / CC BY 4.0" in txt
        assert 'href="method.html#citation"' in txt
        expected_pack = 'packs/v1/protocol-v1.json' if hp.name == 'v1.html' else 'packs/v2/protocol-v2.json'
        assert f'href="{expected_pack}"' in txt

    # Internal link + fragment resolver across every HTML page.
    for pname, p in parsed.items():
        for raw_link in p.links:
            if not raw_link or raw_link.startswith(("http://", "https://", "data:", "mailto:")):
                continue
            path_part, _, frag = raw_link.partition("#")
            path_part = path_part.split("?", 1)[0]
            target_file = out / (path_part or pname)
            assert target_file.exists(), f"broken link in {pname}: {raw_link}"
            if frag:
                target_name = target_file.name
                assert target_name in parsed and frag in parsed[target_name].ids, (
                    f"broken fragment in {pname}: {raw_link}"
                )

    # C2.1 Hero above-the-fold CTA on index.html
    idx_txt = (out / "index.html").read_text(encoding="utf-8")
    assert 'href="chat.html#chat-board">See the table</a>' in idx_txt
    assert 'href="submit.html">Submit your memory</a>' in idx_txt

    # C2.2 Sortable & filterable table on chat.html
    chat_txt = (out / "chat.html").read_text(encoding="utf-8")
    assert 'data-sortable="1"' in chat_txt
    assert 'data-sort-col="wrong"' in chat_txt
    assert 'data-sort-col="withheld"' in chat_txt
    assert 'data-sort-col="right"' in chat_txt
    assert 'class="decider-select"' in chat_txt
    assert 'id="reproduce"' in chat_txt

    # C2.3 Stacked 5-cause bars
    assert '<svg class="cause-svg"' in chat_txt
    assert '<svg class="cause-svg"' in idx_txt

    # C2.4 Product pages
    g_txt = (out / "product-graphiti.html").read_text(encoding="utf-8")
    assert "JSONDecodeError" in g_txt and "ctab2026112302-0036" in g_txt
    assert 'href="packs/v2/excused_ingest_errors.json"' in g_txt
    m_txt = (out / "product-mem0.html").read_text(encoding="utf-8")
    assert "AttributeError" in m_txt and "ctab2026112302-0025" in m_txt

    # C2.5 Submit worked example
    sub_txt = (out / "submit.html").read_text(encoding="utf-8")
    assert "ToyKeywordAdapter" in sub_txt
    assert "Step 1:" in sub_txt and "Step 4:" in sub_txt
    assert "uv run bench site serve --port 8795" in sub_txt


def test_r12_site_serve_cli_loopback(tmp_path: Path) -> None:
    """bench site serve binds loopback and serves built HTML cleanly."""
    out = tmp_path / "dist"
    build_site(ROOT, out, built_at="2026-11-25T15:30:00+00:00")
    proc = subprocess.Popen(
        [
            sys.executable,
            "-m",
            "memory_bench.cli",
            "site",
            "serve",
            "--dir",
            str(out),
            "--host",
            "127.0.0.1",
            "--port",
            "0",
        ],
        cwd=str(ROOT),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        env={**os.environ, "PYTHONPATH": str(ROOT / "src")},
    )
    try:
        assert proc.stdout is not None
        line = proc.stdout.readline().strip()
        m = re.search(r"http://127\.0\.0\.1:(\d+)/", line)
        assert m is not None, f"unexpected stdout: {line!r}"
        port = int(m.group(1))
        time.sleep(0.1)
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/index.html", timeout=5) as resp:
            assert resp.status == 200
            body = resp.read(2048).decode("utf-8")
            assert "Hercyna" in body
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/product-graphiti.html", timeout=5) as resp2:
            assert resp2.status == 200
        req_gz = urllib.request.Request(
            f"http://127.0.0.1:{port}/chat.html", headers={"Accept-Encoding": "gzip"}
        )
        with urllib.request.urlopen(req_gz, timeout=5) as resp3:
            assert resp3.status == 200
            assert resp3.headers.get("Content-Encoding") == "gzip"
            chat_html = gzip.decompress(resp3.read()).decode("utf-8")
            assert "Chat Agent Track" in chat_html
    finally:
        proc.terminate()
        proc.wait(timeout=5)
